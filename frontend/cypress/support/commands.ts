/// <reference types="cypress" />
/// <reference types="cypress-file-upload" />

declare namespace Cypress {
  interface Chainable<Subject = any> {
    /**
     * Log in a user via the API and store the JWT for subsequent requests.
     * @param email User email address
     * @param password User password
     */
    login(email: string, password: string): Chainable<void>;

    /**
     * Remove the stored JWT and clear any auth artefacts from the browser.
     */
    logout(): Chainable<void>;

    /**
     * Store a JWT token in Cypress env and localStorage.
     * @param token JWT string
     */
    setAuthToken(token: string): Chainable<void>;

    /**
     * Wrapper around `cy.request` that automatically injects the Authorization header
     * when a token is present in Cypress.env('authToken').
     */
    api<T = any>(options: Partial<Cypress.RequestOptions>): Chainable<Cypress.Response<T>>;

    /**
     * Upload a file to the platform using the presigned‑URL flow.
     * Returns the created document ID.
     * @param filePath Path to the fixture file (relative to cypress/fixtures)
     * @param tenantId Optional tenant identifier – if omitted the API will infer it from the JWT.
     */
    uploadDocument(
      filePath: string,
      tenantId?: string,
    ): Chainable<{ documentId: string; status: string }>;

    /**
     * Delete a document by its UUID.
     */
    deleteDocument(documentId: string): Chainable<void>;

    /**
     * Create a webhook subscription.
     * @param url Destination URL that will receive events.
     * @param events Array of event names (e.g. ['document.processed']).
     * @param secret Optional secret used for HMAC signing. If omitted a random secret is generated by the backend.
     */
    createWebhook(
      url: string,
      events: string[],
      secret?: string,
    ): Chainable<any>;

    /**
     * Delete a webhook subscription.
     */
    deleteWebhook(webhookId: string): Chainable<void>;
  }
}

/**
 * Helper to retrieve the base API URL from Cypress environment.
 */
function getApiUrl(): string {
  const url = Cypress.env('apiUrl');
  if (!url) {
    throw new Error(
      "Cypress environment variable 'apiUrl' is not defined. Add it to cypress.env.json or CI env.",
    );
  }
  return url.replace(/\/+$/, ''); // strip trailing slash
}

/**
 * ----------------------------------------------------------------------
 * Auth handling
 * ----------------------------------------------------------------------
 */
Cypress.Commands.add('setAuthToken', (token: string) => {
  // Persist token in Cypress env – used by the `api` command.
  Cypress.env('authToken', token);

  // Also store it in localStorage so the application can read it on page load.
  cy.window({ log: false }).then((win) => {
    win.localStorage.setItem('authToken', token);
  });
});

Cypress.Commands.add('login', (email: string, password: string) => {
  const apiUrl = getApiUrl();

  return cy
    .request({
      method: 'POST',
      url: `${apiUrl}/v1/auth/login`,
      body: { email, password },
      failOnStatusCode: false,
    })
    .then((resp) => {
      expect(resp.status, 'login response status').to.eq(200);
      const token = resp.body?.access_token ?? resp.body?.token;
      expect(token, 'JWT token returned from login').to.be.a('string');

      // Store token for later use.
      cy.setAuthToken(token);
    });
});

Cypress.Commands.add('logout', () => {
  // Clear token from Cypress env.
  Cypress.env('authToken', null);

  // Remove from localStorage.
  cy.window({ log: false }).then((win) => {
    win.localStorage.removeItem('authToken');
  });

  // Optionally clear cookies that might be set by OIDC flows.
  cy.clearCookies();
});

/**
 * ----------------------------------------------------------------------
 * Generic API wrapper
 * ----------------------------------------------------------------------
 */
Cypress.Commands.add('api', <T = any>(options: Partial<Cypress.RequestOptions>) => {
  const token = Cypress.env('authToken');
  const defaultHeaders: Record<string, string> = {};

  if (token) {
    defaultHeaders.Authorization = `Bearer ${token}`;
  }

  const mergedOptions: Cypress.RequestOptions = {
    method: 'GET',
    failOnStatusCode: true,
    headers: defaultHeaders,
    ...options,
  };

  return cy.request<T>(mergedOptions);
});

/**
 * ----------------------------------------------------------------------
 * Document helpers
 * ----------------------------------------------------------------------
 */
Cypress.Commands.add(
  'uploadDocument',
  (filePath: string, tenantId?: string) => {
    const apiUrl = getApiUrl();

    // Step 1 – ask the backend for a presigned URL.
    return cy
      .api({
        method: 'POST',
        url: `${apiUrl}/v1/documents`,
        body: {
          filename: filePath.split('/').pop(),
          ...(tenantId && { tenant_id: tenantId }),
        },
      })
      .then((resp) => {
        expect(resp.status, 'presigned URL response').to.eq(201);
        const { upload_url: uploadUrl, document_id: documentId } = resp.body;
        expect(uploadUrl, 'upload_url present').to.be.a('string');
        expect(documentId, 'document_id present').to.be.a('string');

        // Step 2 – read the fixture file as a binary blob.
        return cy
          .fixture(filePath, 'binary')
          .then(Cypress.Blob.binaryStringToBlob)
          .then((fileBlob) => {
            // Step 3 – upload the blob directly to the storage endpoint.
            return cy
              .request({
                method: 'PUT',
                url: uploadUrl,
                body: fileBlob,
                headers: {
                  'Content-Type': 'application/octet-stream',
                },
                // The storage service may return 200, 201 or 204.
                failOnStatusCode: false,
              })
              .then((uploadResp) => {
                expect(
                  uploadResp.status,
                  'upload to storage status',
                ).to.be.oneOf([200, 201, 204]);

                // The document is now in “uploaded” state; the worker will pick it up.
                return { documentId, status: 'uploaded' };
              });
          });
      });
  },
);

/**
 * Delete a document – useful for test clean‑up.
 */
Cypress.Commands.add('deleteDocument', (documentId: string) => {
  const apiUrl = getApiUrl();

  return cy
    .api({
      method: 'DELETE',
      url: `${apiUrl}/v1/documents/${documentId}`,
    })
    .then((resp) => {
      expect(resp.status, 'delete document response').to.be.oneOf([200, 204]);
    });
});

/**
 * ----------------------------------------------------------------------
 * Webhook helpers
 * ----------------------------------------------------------------------
 */
Cypress.Commands.add(
  'createWebhook',
  (url: string, events: string[], secret?: string) => {
    const apiUrl = getApiUrl();

    return cy
      .api({
        method: 'POST',
        url: `${apiUrl}/v1/webhooks`,
        body: {
          url,
          events,
          ...(secret && { secret }),
        },
      })
      .then((resp) => {
        expect(resp.status, 'create webhook response').to.eq(201);
        return resp.body; // contains webhook_id and other metadata
      });
  },
);

Cypress.Commands.add('deleteWebhook', (webhookId: string) => {
  const apiUrl = getApiUrl();

  return cy
    .api({
      method: 'DELETE',
      url: `${apiUrl}/v1/webhooks/${webhookId}`,
    })
    .then((resp) => {
      expect(resp.status, 'delete webhook response').to.be.oneOf([200, 204]);
    });
});

/**
 * ----------------------------------------------------------------------
 * Global error handling for uncaught API errors
 * ----------------------------------------------------------------------
 */
Cypress.on('fail', (error, runnable) => {
  // Provide a more helpful message when an API request fails unexpectedly.
  if (error.message.includes('Timed out retrying')) {
    Cypress.log({
      name: 'API Failure',
      message: `A request to ${error.message.match(/url: (.+?)$/)?.[1] ||
        'unknown endpoint'} failed. Check the backend logs and ensure the API URL (${Cypress.env(
        'apiUrl',
      )}) is reachable.`,
      consoleProps: () => ({
        error,
        runnable,
      }),
    });
  }
  throw error; // re‑throw to keep Cypress default behaviour
});