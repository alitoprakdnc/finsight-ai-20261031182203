package queue

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
	"time"

	"github.com/google/uuid"
)

// TaskType represents the kind of work the worker should perform.
type TaskType string

const (
	// TaskOCR extracts raw text from the uploaded document using Tesseract.
	TaskOCR TaskType = "ocr"
	// TaskLLM parses OCR output with an LLM to produce structured data.
	TaskLLM TaskType = "llm"
)

// TaskPayload is the payload that is sent to the task queue (Google Cloud Tasks or BullMQ).
// It contains enough information for the worker to locate the document, know the tenant
// context and understand which processing step to execute.
type TaskPayload struct {
	// ID is a unique identifier for the task instance. It is generated by the producer
	// and can be used for idempotency checks.
	ID uuid.UUID `json:"id"`

	// Type indicates which processing stage the worker should execute.
	Type TaskType `json:"type"`

	// DocumentID references the document record stored in the database.
	DocumentID uuid.UUID `json:"document_id"`

	// TenantID identifies the tenant (multi‑tenant isolation).
	TenantID uuid.UUID `json:"tenant_id"`

	// Attempt counts how many times this task has been retried.
	// The worker increments this value on each retry.
	Attempt int `json:"attempt"`

	// EnqueuedAt records when the task was created.
	EnqueuedAt time.Time `json:"enqueued_at"`
}

// NewTaskPayload creates a new TaskPayload with sensible defaults.
// The caller must provide the processing type, document ID and tenant ID.
func NewTaskPayload(taskType TaskType, documentID, tenantID uuid.UUID) (*TaskPayload, error) {
	if taskType != TaskOCR && taskType != TaskLLM {
		return nil, fmt.Errorf("unsupported task type: %s", taskType)
	}
	if documentID == uuid.Nil {
		return nil, fmt.Errorf("documentID cannot be nil")
	}
	if tenantID == uuid.Nil {
		return nil, fmt.Errorf("tenantID cannot be nil")
	}

	return &TaskPayload{
		ID:         uuid.New(),
		Type:       taskType,
		DocumentID: documentID,
		TenantID:   tenantID,
		Attempt:    0,
		EnqueuedAt: time.Now().UTC(),
	}, nil
}

// Validate checks the payload for required fields.
// It is used both before enqueuing and after deserialization.
func (p *TaskPayload) Validate() error {
	if p.ID == uuid.Nil {
		return fmt.Errorf("task ID is required")
	}
	if p.Type != TaskOCR && p.Type != TaskLLM {
		return fmt.Errorf("invalid task type: %s", p.Type)
	}
	if p.DocumentID == uuid.Nil {
		return fmt.Errorf("document ID is required")
	}
	if p.TenantID == uuid.Nil {
		return fmt.Errorf("tenant ID is required")
	}
	if p.EnqueuedAt.IsZero() {
		return fmt.Errorf("enqueuedAt timestamp is required")
	}
	return nil
}

// MarshalJSON returns the JSON representation of the payload.
// It satisfies the json.Marshaler interface.
func (p *TaskPayload) MarshalJSON() ([]byte, error) {
	type alias TaskPayload // avoid recursion
	return json.Marshal((*alias)(p))
}

// UnmarshalJSON parses a JSON payload into the struct.
// It also validates the resulting object.
func (p *TaskPayload) UnmarshalJSON(data []byte) error {
	type alias TaskPayload
	var tmp alias
	if err := json.Unmarshal(data, &tmp); err != nil {
		return err
	}
	*p = TaskPayload(tmp)
	return p.Validate()
}

// EncodeBase64 serialises the payload to JSON and then base64‑encodes it.
// This is the format expected by Google Cloud Tasks (payload field) and
// by BullMQ when using a string payload.
func (p *TaskPayload) EncodeBase64() (string, error) {
	if err := p.Validate(); err != nil {
		return "", err
	}
	b, err := json.Marshal(p)
	if err != nil {
		return "", fmt.Errorf("failed to marshal task payload: %w", err)
	}
	return base64.StdEncoding.EncodeToString(b), nil
}

// DecodeBase64 decodes a base64‑encoded JSON string into a TaskPayload.
// It validates the resulting payload before returning.
func DecodeBase64(encoded string) (*TaskPayload, error) {
	if encoded == "" {
		return nil, fmt.Errorf("encoded payload is empty")
	}
	b, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return nil, fmt.Errorf("base64 decode failed: %w", err)
	}
	var payload TaskPayload
	if err := json.Unmarshal(b, &payload); err != nil {
		return nil, fmt.Errorf("json unmarshal failed: %w", err)
	}
	if err := payload.Validate(); err != nil {
		return nil, fmt.Errorf("invalid task payload: %w", err)
	}
	return &payload, nil
}

// IncrementAttempt returns a new TaskPayload with the Attempt counter increased.
// It does not modify the original payload, preserving immutability for logging.
func (p *TaskPayload) IncrementAttempt() *TaskPayload {
	newPayload := *p
	newPayload.Attempt++
	return &newPayload
}